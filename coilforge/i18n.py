def normalize_language(value):
    if not value:
        return None
    text = str(value).strip().lower().replace("-", "_")
    if not text:
        return None
    if text in ("default", "system", "system default", "默认", "預設", "系统默认", "系統預設"):
        return None
    chinese_markers = ("zh", "chinese", "中文", "汉语", "漢語", "简体", "繁體")
    if any(text.startswith(marker) or marker in text for marker in chinese_markers):
        return "zh"
    return "en"


def language_from_kicad_config(path):
    try:
        with open(path, "r", encoding="utf-8") as config_file:
            data = json.load(config_file)
        return normalize_language(data.get("system", {}).get("language"))
    except (IOError, OSError, ValueError, TypeError, AttributeError):
        return None


def _language_from_system_wx(wx_module):
    if wx_module is None:
        return None
    try:
        locale_type = getattr(wx_module, "Locale", None)
        if locale_type is not None:
            language_id = locale_type.GetSystemLanguage()
            language_info = locale_type.GetLanguageInfo(language_id)
            if language_info:
                for attribute in ("CanonicalName", "Description"):
                    detected = normalize_language(getattr(language_info, attribute, None))
                    if detected:
                        return detected
    except Exception:
        pass
    return None


def detect_language(pcbnew_module=None, wx_module=None, environ=None,
                    locale_name=None, kicad_config_path=None,
                    kicad_version=None, platform_name=None, home=None):
    """Detect Chinese or English, preferring active KiCad configuration."""
    env = os.environ if environ is None else environ
    config_path = None
    if kicad_config_path:
        expanded = os.path.abspath(os.path.expanduser(str(kicad_config_path)))
        config_path = (
            os.path.join(expanded, "kicad_common.json")
            if os.path.isdir(expanded)
            else expanded
        )
    elif (
            pcbnew_module is not None
            or kicad_version is not None
            or env.get("KICAD_CONFIG_HOME")):
        config_path = active_kicad_common_path(
            pcbnew_module=pcbnew_module,
            kicad_version=kicad_version,
            environ=env,
            platform_name=platform_name,
            home=home,
        )
    detected = language_from_kicad_config(config_path) if config_path else None
    if detected:
        return detected

    # An explicit KiCad environment override is still a KiCad language choice.
    detected = normalize_language(env.get("KICAD_LANGUAGE"))
    if detected:
        return detected

    detected = _language_from_system_wx(wx_module)
    if detected:
        return detected

    for key in ("LANGUAGE", "LC_ALL", "LC_MESSAGES", "LANG"):
        detected = normalize_language(env.get(key))
        if detected:
            return detected

    if locale_name is None:
        try:
            locale_name = locale.getlocale()[0]
        except (ValueError, TypeError):
            locale_name = None
    return normalize_language(locale_name) or "en"



class Translator(object):
    def __init__(self, language):
        self.language = language if language in TRANSLATIONS else "en"

    def __call__(self, key, **values):
        text = TRANSLATIONS[self.language].get(key, TRANSLATIONS["en"].get(key, key))
        return text.format(**values) if values else text


def localize_error(translator, error):
    """Translate stable exception codes while preserving unknown diagnostics."""
    code = getattr(error, "code", None) or str(error) or error.__class__.__name__
    values = dict(getattr(error, "values", {}) or {})
    try:
        translated = translator(code, **values) if values else translator(code)
    except (KeyError, IndexError, ValueError):
        translated = code
    return translated if translated != code else (str(error) or code)






